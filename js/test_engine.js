const fs = require('fs');
const vm = require('vm');
const source = fs.readFileSync('./engine.js', 'utf8');
const ctx = { console };
vm.createContext(ctx);
vm.runInContext(source, ctx);

const HARD = `অঙ্ক অঙ্ক্ষ ক্ক ক্ট ক্ত ক্ব ক্র ক্ল ক্ষ ক্ষ্ম ক্স গ্ধ গ্ন গ্ম গ্ল গু চ্চ চ্ছ চ্ছ্ব চ্ঞ জ্জ জ্জ্ব জ্ঝ জ্ঞ জ্ব ঞ্চ ঞ্ছ ঞ্জ ঞ্ঝ ট্ট ট্ব ট্ম ড্ড ণ্ট ণ্ঠ ণ্ড ণ্ব ত্ত ত্ত্ব ত্থ ত্ম ত্ব ত্র থ্ব দ্গ দ্ঘ দ্দ দ্ধ দ্ব দ্ভ দ্ম দ্র ধ্ব ধ্ম ন্ট ন্ঠ ন্ড ন্ত ন্তু ন্থ ন্ত্ব ন্ত্র ন্ত্র্য ন্দ ন্দ্ব ন্ধ ন্ন ন্ব ন্ম ন্স প্ট প্ত প্ন প্প প্ল প্স ফ্ল ব্জ ব্দ ব্ধ ব্ব ব্ল ভ্র ম্ন ম্প ম্ফ ম্ব ম্ভ ম্ভ্র ম্ম ম্ল রু রূ ল্ক ল্গ ল্ট ল্ড ল্প ল্ফ ল্ব ল্ম ল্ল শ্চ শ্ন শ্ব শ্ম শ্ল ষ্ক ষ্ক্র ষ্ট ষ্ঠ ষ্ণ ষ্প ষ্ফ ষ্ম স্ক স্ক্র স্ট স্খ স্ত স্তু স্থ স্ত্র স্ন স্প স্ফ স্ব স্ম স্ল হু হ্ণ হ্ন হ্ম হ্ল হৃ প্র গ্র দ্র ব্র ভ্র শ্র র্য র্ত র্দ র্ধ র্ম র্ব র্শ র্ষ র্স স্বাতন্ত্র্য কর্তৃত্ব দৈর্ঘ্য বৈচিত্র্য সৌহার্দ্য শ্রদ্ধাঞ্জলি ব্রহ্ম প্রত্যক্ষদর্শী কার্যপ্রণালীর প্রশাসনিক প্রয়োজনীয় সংশ্লিষ্ট সম্পৃক্ত অনুমোদন যাচাইকরণ জটিলতা যথাযথ পুনর্বিন্যাস আনুষঙ্গিক প্রক্রিয়াসমূহ`.split(/\s+/);
const paragraph = `বিষয়: প্রয়োজনীয় প্রশাসনিক কার্যক্রম সম্পাদনের জন্য বিশেষ আবেদন।\nজনাব/জনাবা,\nসাবিনয় নিবেদন এই যে, আমি আপনার প্রতিষ্ঠানের একজন নিয়মিত শিক্ষার্থী/কর্মী।\nদীর্ঘদিন যাবৎ সংশ্লিষ্ট কার্যক্রমের সঙ্গে সম্পৃক্ত থাকার সুবাদে প্রতিষ্ঠানের বিভিন্ন প্রশাসনিক ও প্রাতিষ্ঠানিক কার্যপ্রণালীর সঙ্গে পরিচিত হওয়ার সুযোগ হয়েছে।\nসম্প্রতি অনিবার্য পরিস্থিতির উদ্ভূত জটিলতার কারণে আমার নির্ধারিত কার্যক্রম যথাসময়ে সম্পন্ন করা সম্ভবপর হয়ে উঠছে না।\nউক্ত পরিস্থিতিতে প্রয়োজনীয় নথিপত্রের যথাযথ যাচাইকরণ, সংশ্লিষ্ট কর্তৃপক্ষের অনুমোদন, নির্ধারিত সময়সীমার পুনর্বিন্যাস এবং আনুষঙ্গিক প্রক্রিয়াসমূহের সমন্বয় সাধনের জন্য আপনার সদয় বিবেচনা একান্তভাবে কাম্য।`;

let pass = 0, fail = 0;
for (const text of HARD) {
  const b = ctx.unicodeToBijoy(text);
  const u = ctx.bijoyToUnicode(b);
  if (u === text || (text === 'য়' && u === 'য়')) pass++;
  else { fail++; console.log('FAIL:', text, '=>', b, '=>', u); }
}
const pb = ctx.unicodeToBijoy(paragraph);
const pu = ctx.bijoyToUnicode(pb);
if (pu === paragraph) pass++; else { fail++; console.log('FAIL: paragraph round-trip'); }
const mixed = ctx.bijoyToUnicode('Avgvi ‡mvbvi evsjv This is English text.');
if (mixed === 'আমার সোনার বাংলা This is English text.') pass++; else { fail++; console.log('FAIL: mixed English/Bijoy:', mixed); }
console.log(`PASS=${pass} FAIL=${fail} TOTAL=${pass+fail}`);
process.exitCode = fail ? 1 : 0;
